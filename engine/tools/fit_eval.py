#!/usr/bin/env python3
"""Fit a candidate evaluator header from the engine's analyze feature ABI."""

import argparse
import json
import math
import subprocess
from pathlib import Path


def solve(matrix: list[list[float]], vector: list[float]) -> list[float]:
    n = len(vector)
    augmented = [matrix[i][:] + [vector[i]] for i in range(n)]
    for column in range(n):
        pivot = max(range(column, n), key=lambda row: abs(augmented[row][column]))
        augmented[column], augmented[pivot] = augmented[pivot], augmented[column]
        divisor = augmented[column][column]
        if abs(divisor) < 1e-15:
            continue
        augmented[column] = [value / divisor for value in augmented[column]]
        for row in range(n):
            if row == column:
                continue
            factor = augmented[row][column]
            augmented[row] = [
                augmented[row][cell] - factor * augmented[column][cell]
                for cell in range(n + 1)
            ]
    return [augmented[i][n] for i in range(n)]


def fit(features: list[list[float]], labels: list[float]) -> list[float]:
    width = len(features[0])
    normal = [[0.0] * width for _ in range(width)]
    rhs = [0.0] * width
    for row, label in zip(features, labels, strict=True):
        for i in range(width):
            rhs[i] += row[i] * label
            for j in range(width):
                normal[i][j] += row[i] * row[j]
    for i in range(width):
        normal[i][i] += 1e-9
    return solve(normal, rhs)


def sigmoid(value: float) -> float:
    if value >= 0.0:
        decay = math.exp(-value)
        return 1.0 / (1.0 + decay)
    growth = math.exp(value)
    return growth / (1.0 + growth)


def logit_midpoint(midpoint: float) -> float:
    clipped = min(max(midpoint, 1e-6), 1.0 - 1e-6)
    return math.log(clipped / (1.0 - clipped))


def self_test() -> None:
    features = [[1.0, 0.0], [1.0, 1.0], [1.0, 2.0], [1.0, 3.0]]
    midpoints = [sigmoid(-1.0 + value) for value in range(4)]
    weights = fit(features, [logit_midpoint(value) for value in midpoints])
    predictions = [sigmoid(sum(w * x for w, x in zip(weights, row, strict=True)))
                   for row in features]
    if max(abs(actual - expected)
           for actual, expected in zip(predictions, midpoints, strict=True)) > 1e-8:
        raise SystemExit("sigmoid parameterization self-test failed")


def write_header(path: Path, weights: list[float]) -> None:
    values = ",\n    ".join(f"{weight:.17g}" for weight in weights)
    path.write_text(
        "#pragma once\n\n#include <array>\n\nnamespace uttt {\n\n"
        "// Candidate generated by engine/tools/fit_eval.py.\n"
        f"inline constexpr std::array<double, {len(weights)}> kEvalWeights = {{\n"
        f"    {values}\n}};\n\n}} // namespace uttt\n",
        encoding="utf-8",
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--engine", type=Path)
    parser.add_argument("--corpus", type=Path)
    parser.add_argument("--out", type=Path)
    parser.add_argument("--depth", type=int, default=6)
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    if args.self_test:
        self_test()
        print("fit_eval sigmoid parameterization self-test: PASS")
        return 0
    if args.engine is None or args.corpus is None or args.out is None:
        parser.error("--engine, --corpus, and --out are required")

    requests = []
    with args.corpus.open(encoding="utf-8") as corpus:
        for line in corpus:
            request = json.loads(line)
            request["depth"] = args.depth
            requests.append(request)
    if len(requests) != 2000:
        raise SystemExit(f"corpus must contain 2000 positions, found {len(requests)}")

    process = subprocess.run(
        [str(args.engine), "analyze"],
        input="".join(json.dumps(request, separators=(",", ":")) + "\n"
                      for request in requests),
        text=True,
        capture_output=True,
        check=True,
    )
    replies = [json.loads(line) for line in process.stdout.splitlines()]
    if len(replies) != len(requests):
        raise SystemExit("engine returned the wrong number of analyze rows")
    features = [reply["features"] for reply in replies]
    labels = [(reply["t_lo"] + reply["t_hi"]) / 2.0 for reply in replies]
    weights = fit(features, [logit_midpoint(label) for label in labels])
    write_header(args.out, weights)
    mean_squared_error = sum(
        (sigmoid(sum(weight * value for weight, value in zip(weights, row, strict=True))) - label) ** 2
        for row, label in zip(features, labels, strict=True)
    ) / len(labels)
    print(f"fit rows={len(labels)} features={len(weights)} mse={mean_squared_error:.12g}")
    print(f"candidate={args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
